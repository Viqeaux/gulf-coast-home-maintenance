def article_ld(page):
    return json.dumps({
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "Article",
                "headline": page["og_title"],
                "description": page["og_description"],
                "datePublished": ISO,
                "dateModified": ISO,
                "author": {"@type": "Organization",
                           "name": "Gulf Coast Home Maintenance",
                           "url": "https://gulfcoasthomemaintenance.com/"},
                "mainEntityOfPage":
                    "https://gulfcoasthomemaintenance.com/resources/%s/" % page["slug"],
            },
            {
                "@type": "BreadcrumbList",
                "itemListElement": [
                    {"@type": "ListItem", "position": 1,
                     "name": "Gulf Coast Home Maintenance",
                     "item": "https://gulfcoasthomemaintenance.com/"},
                    {"@type": "ListItem", "position": 2, "name": "Grants and programs",
                     "item": "https://gulfcoasthomemaintenance.com/resources/"},
                    {"@type": "ListItem", "position": 3, "name": page["h1"]},
                ],
            },
        ],
    }, indent=2, ensure_ascii=False)


def render(page):
    rows = "\n".join(
        '        <li><a href="{0}">{1}</a>\n          <span class="what">&middot; {2}</span></li>'
        .format(href, label, what) for href, label, what in page["next"])
    return SHELL.format(structured=article_ld(page), next_rows=rows, **page)


def main():
    from resource_content import PAGES
    for page in PAGES:
        folder = os.path.join(OUT, page["slug"])
        os.makedirs(folder, exist_ok=True)
        path = os.path.join(folder, "index.html")
        io.open(path, "w", encoding="utf-8", newline="\n").write(render(page))
        print("  %s" % path)
    print("%d resource pages generated" % len(PAGES))
    print("Now run build_chrome.py so they get the bar and the footer.")


if __name__ == "__main__":
    main()
