#!/usr/bin/env python3
"""Generate the resource pages added from 1.38.0 on.

Why a generator
---------------
The first seven resource pages were hand-written, and each carried its own copy
of the same 71 line stylesheet. Two had already drifted apart by the time the
audit found them, which is what produced docs/resources.css in 1.37.0. The
shell of one of these pages -- the head, the CSP, the crumbs, the checked
stamp, the read-next box, the limits section -- is the same shape every time,
so it lives here rather than being pasted an eighth time.

The bar and the footer are not here. Those come from site_chrome.py, written in
by build_chrome.py, same as every other page.

The rule these pages follow, unchanged from the shelf they join
--------------------------------------------------------------
This site organizes the question. The institution keeps the answer. Every fact
attributed to an agency was read on that agency's own page on the date in
CHECKED, and the page says so. Where a figure varies by policy, by carrier or
by state, this says that it varies and sends the reader to the document that
decides -- it does not print a number that would be wrong for most readers.

Adding a page: add an entry to PAGES, add it to RESOURCES in site_chrome.py, a
row on docs/resources/index.html, a RESOURCE_CHECKED entry in build_chrome.py,
and a sitemap entry. Then run this and build_chrome.py.
"""

